import assert from "node:assert/strict";
import { mockAckFan, mockClearMyData, mockCreateCampaign, mockCreatePass, mockDeleteFan, mockEditGrant, mockGetFanDetail, mockGetFanPass, mockListFans, mockReconcileCreatorRequest, mockSelfExclude, mockSetFanBlocked, mockSpin } from "./mock";
import { mockCreatorRequests } from "./mockCreatorRequests";

let passed = 0;
function check(label: string, value: unknown) { assert.ok(value, label); passed++; }
async function main() {
  const made = mockCreatePass("Private edit retry fan", 10);
  const grant = mockGetFanDetail(made.fanId)!.grants[0];
  const original = crypto.randomUUID();
  const first = mockEditGrant(grant.id, { spins: 20, amountCents: 200 }, original);
  check("original edit commits its captured intent", "ok" in first && !first.replayed && first.requestId === original && first.spinsRemaining === 20);
  const newer = mockEditGrant(grant.id, { spins: 12, amountCents: 120 }, crypto.randomUUID());
  check("a later deliberate edit commits independently", "ok" in newer && newer.spinsRemaining === 12);
  const replay = mockEditGrant(grant.id, { amountCents: 200, spins: 20 }, original);
  check("lost-reply retry cannot overwrite the newer grant", "ok" in replay && replay.replayed && replay.grant.spins === 12 && replay.grant.amountCents === 120 && replay.spinsRemaining === 12);
  check("late replay keeps aggregate equal to the active pass sum", mockListFans().find(fan => fan.fanId === made.fanId)!.spinsRemaining === 12 && (await mockGetFanPass(made.token))!.spinsRemaining === 12);
  const conflict = mockEditGrant(grant.id, { spins: 21, amountCents: 200 }, original);
  check("same ID with altered raw patch conflicts", "error" in conflict && conflict.error === "conflict" && (await mockGetFanPass(made.token))!.spinsRemaining === 12);
  const presence = mockEditGrant(grant.id, { spins: 12 }, crypto.randomUUID()); assert.ok("ok" in presence);
  const presenceConflict = mockEditGrant(grant.id, { spins: 12, amountCents: 120 }, presence.requestId);
  check("omitted and explicitly present fields bind different intents", "error" in presenceConflict && presenceConflict.error === "conflict");
  const campaign = mockCreateCampaign("Edit campaign");
  const tagged = mockEditGrant(grant.id, { campaignId: campaign.id }); assert.ok("ok" in tagged);
  const amountOnly = mockEditGrant(grant.id, { amountCents: 130 });
  check("omitted campaign is derived from current locked terms", "ok" in amountOnly && amountOnly.grant.campaignId === campaign.id);
  const cleared = mockEditGrant(grant.id, { campaignId: null }, crypto.randomUUID()); assert.ok("ok" in cleared);
  const clearConflict = mockEditGrant(grant.id, {}, cleared.requestId);
  check("explicit campaign null is bound distinctly from omission", "error" in clearConflict && clearConflict.error === "conflict" && cleared.grant.campaignId === null);
  const cancelled = crypto.randomUUID();
  check("unseen edit is not terminal until explicitly cancelled", mockReconcileCreatorRequest(cancelled, "edit", false).status === "absent");
  check("cancellation creates an exact edit fence", mockReconcileCreatorRequest(cancelled, "edit", true).status === "cancelled");
  const late = mockEditGrant(grant.id, { spins: 99 }, cancelled);
  check("delayed edit cannot land after confirmed cancellation", "error" in late && late.error === "cancelled" && (await mockGetFanPass(made.token))!.spinsRemaining === 12);
  const otherKind = mockEditGrant(grant.id, { spins: 99 }, "not-a-request-uuid");
  check("invalid intent UUID cannot mutate a grant", "error" in otherKind && otherKind.error === "invalid");
  const passCancelled = crypto.randomUUID(); mockReconcileCreatorRequest(passCancelled, "pass", true);
  check("request kind cannot be changed to evade a cancellation", "error" in mockEditGrant(grant.id, {}, passCancelled) && mockReconcileCreatorRequest(passCancelled, "edit", false).status === "conflict");
  for (const patch of [{ spins: 1.5 }, { spins: NaN }, { spins: -1 }, { amountCents: Infinity }, { amountCents: 100_000_001 }, { spins: null }, { amountCents: null }]) {
    const result = mockEditGrant(grant.id, patch as { spins?: number; amountCents?: number });
    check("invalid numeric patch cannot write", "error" in result && result.error === "invalid");
  }
  const rejectedId = crypto.randomUUID(); mockEditGrant(grant.id, { spins: -1 }, rejectedId);
  const rejectedRetry = mockEditGrant(grant.id, { spins: -1 }, rejectedId), rejectedChanged = mockEditGrant(grant.id, { spins: 12 }, rejectedId);
  check("rejected raw intent is terminal and cannot be repurposed", "error" in rejectedRetry && rejectedRetry.error === "rejected" && "error" in rejectedChanged && rejectedChanged.error === "conflict" && mockReconcileCreatorRequest(rejectedId, "edit", false).status === "rejected");
  mockAckFan(made.token);
  const won = await mockSpin(made.token, "edit-replay-after-spend"); assert.ok(!("error" in won));
  const spentReplay = mockEditGrant(grant.id, { spins: 20, amountCents: 200 }, original);
  check("replay reports current balance after a subsequent spin", "ok" in spentReplay && spentReplay.spinsRemaining === 11 && spentReplay.grant.spins === 12);
  const metadata = JSON.stringify([...mockCreatorRequests().values()].filter(entry => entry.kind === "edit"));
  check("edit journal exports only digest and metadata", !metadata.includes(made.token) && !metadata.includes("Private edit retry fan") && !metadata.includes('"spins":') && !metadata.includes('"amountCents":'));
  mockSetFanBlocked(made.fanId, true);
  const blockedReplay = mockEditGrant(grant.id, { spins: 20, amountCents: 200 }, original);
  check("new F6 restrictions do not erase an existing edit receipt", "ok" in blockedReplay && blockedReplay.replayed && blockedReplay.spinsRemaining === 11);
  const blockedNew = mockEditGrant(grant.id, { spins: 13 });
  check("new increasing edit fails closed under F6", "error" in blockedNew && blockedNew.error === "blocked");
  mockSetFanBlocked(made.fanId, false);
  const bonusFan = mockCreatePass("Bonus edit", 10, undefined, undefined, undefined, 5);
  const bonusGrant = mockGetFanDetail(bonusFan.fanId)!.grants[0];
  const reducedBonus = mockEditGrant(bonusGrant.id, { spins: 3 });
  check("spin edit derives the bonus subset from locked grant terms", "ok" in reducedBonus && reducedBonus.grant.bonusSpins === 3 && reducedBonus.spinsRemaining === 3);
  mockSelfExclude(bonusFan.token);
  const noPass = mockEditGrant(bonusGrant.id, { amountCents: 80 });
  check("metadata-only edit truthfully reports no active pass", "ok" in noPass && noPass.spinsRemaining === null && noPass.grant.spins === 3 && noPass.grant.bonusSpins === 3);
  const creditWithoutPass = mockEditGrant(bonusGrant.id, { spins: 4 });
  check("an actual balance change needs an active pass", "error" in creditWithoutPass && creditWithoutPass.error === "no_active_pass");
  mockDeleteFan(made.fanId);
  const erased = mockEditGrant(grant.id, { spins: 20, amountCents: 200 }, original);
  check("erasure leaves a gone edit tombstone instead of recreating credits", "error" in erased && erased.error === "gone" && mockReconcileCreatorRequest(original, "edit", false).status === "gone");
  check("erased edit metadata contains no business references", !JSON.stringify([...mockCreatorRequests().values()].filter(entry => entry.kind === "edit")).includes(made.fanId));
  const resetFan = mockCreatePass("Reset edit fan", 2);
  const resetGrant = mockGetFanDetail(resetFan.fanId)!.grants[0], resetId = crypto.randomUUID();
  assert.ok("ok" in mockEditGrant(resetGrant.id, { spins: 3 }, resetId));
  mockClearMyData();
  const resetReplay = mockEditGrant(resetGrant.id, { spins: 3 }, resetId);
  check("account reset preserves a terminal fence for delayed edits", "error" in resetReplay && resetReplay.error === "gone" && mockListFans().length === 0);
  console.log(`mock grant edit intents: ${passed} checks passed`);
}
main().catch(error => { console.error(error); process.exit(1); });
